import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import vm from 'node:vm'

const UPSTREAM_REPOSITORY = 'mathruffian-dot/yizi-qianjin-practice'
const UPSTREAM_COMMIT = '588cb8eabab92f42f73b4f8e3bf4873a8ed003c9'
const RAW_ROOT = `https://raw.githubusercontent.com/${UPSTREAM_REPOSITORY}/${UPSTREAM_COMMIT}`
const projectRoot = resolve(import.meta.dirname, '..')

async function fetchText(fileName) {
  const response = await fetch(`${RAW_ROOT}/${fileName}`)
  if (!response.ok) throw new Error(`無法下載 ${fileName}：HTTP ${response.status}`)
  return response.text()
}

function loadQuestionData(source) {
  const context = {}
  vm.runInNewContext(`${source}\n;globalThis.__exported = { QW, SS, PAIRS, IDIOMS_COMMON };`, context)
  return context.__exported
}

function loadAcceptedIdioms(source) {
  const context = { window: {} }
  vm.runInNewContext(source, context)
  return String(context.window.IDIOMS_ACCEPT || '').split(/\s+/).filter(Boolean)
}

function stableKey(gameType, prompt) {
  const digest = createHash('sha256').update(JSON.stringify(prompt)).digest('hex').slice(0, 20)
  return `yzqj-${gameType}-${digest}`
}

function sqlString(value) {
  return `'${String(value ?? '').replaceAll("'", "''")}'`
}

function questionRows(data) {
  return [
    ...data.QW.map((item) => {
      const prompt = { parts: item.p, removedPart: item.d || '' }
      return {
        stableKey: stableKey('remove_part', prompt),
        gameType: 'remove_part', difficulty: Number(item.lv || 1),
        prompt, answers: { accepted: [item.a, ...(item.alt || [])] },
      }
    }),
    ...data.SS.map((item) => {
      const prompt = { idioms: item.q, targetIndices: item.i }
      return {
        stableKey: stableKey('four_sayings', prompt),
        gameType: 'four_sayings', difficulty: Number(item.lv || 1),
        prompt, answers: { accepted: [item.a, ...(item.alt || [])] },
      }
    }),
    ...data.PAIRS.map((item) => {
      const prompt = { title: item.name, parts: item.grid }
      return {
        stableKey: stableKey('component_pairs', prompt),
        gameType: 'component_pairs', difficulty: Number(item.lv || 1),
        prompt, answers: { accepted: item.ans || [], extra: item.extra || [] },
      }
    }),
  ]
}

function buildSeedMigration(questions, commonIdioms, acceptedIdioms) {
  const questionSql = questions.map((question) => `(
    ${sqlString(question.stableKey)}, ${sqlString(question.gameType)}, ${question.difficulty},
    ${sqlString(JSON.stringify(question.prompt))}::jsonb,
    ${sqlString(JSON.stringify(question.answers))}::jsonb,
    'published', '一字千金練習系統',
    'https://github.com/${UPSTREAM_REPOSITORY}', '${UPSTREAM_COMMIT}'
  )`).join(',\n')
  const acceptedText = acceptedIdioms.join(' ')
  const commonText = commonIdioms.join(' ')
  return `-- Generated by scripts/sync-yizi-qianjin-data.mjs. Do not edit by hand.
-- Upstream commit: ${UPSTREAM_COMMIT}

insert into public.yizi_questions (
  stable_key, game_type, difficulty, prompt_data, answer_data, status,
  source_label, source_url, source_commit
)
values
${questionSql}
on conflict (stable_key) do update set
  difficulty = excluded.difficulty,
  prompt_data = excluded.prompt_data,
  answer_data = excluded.answer_data,
  source_label = excluded.source_label,
  source_url = excluded.source_url,
  source_commit = excluded.source_commit,
  updated_at = now();

insert into public.yizi_idiom_lexicon (phrase, is_common, source_commit)
select distinct phrase, false, '${UPSTREAM_COMMIT}'
from unnest(string_to_array($yizi$${acceptedText}$yizi$, ' ')) as phrase
where char_length(phrase) = 4
on conflict (phrase) do update set source_commit = excluded.source_commit;

with ranked as (
  select phrase, ordinal::integer as common_rank
  from unnest(string_to_array($common$${commonText}$common$, ' ')) with ordinality as entry(phrase, ordinal)
)
update public.yizi_idiom_lexicon target
set is_common = true, common_rank = ranked.common_rank
from ranked
where target.phrase = ranked.phrase;
`
}

const [dataSource, idiomSource] = await Promise.all([
  fetchText('data.js'),
  fetchText('idioms.js'),
])
const data = loadQuestionData(dataSource)
const questions = questionRows(data)
const commonIdioms = String(data.IDIOMS_COMMON || '').split(/\s+/).filter(Boolean)
const acceptedIdioms = loadAcceptedIdioms(idiomSource)

const dataPath = resolve(projectRoot, 'src/data/yiziQianjinQuestions.json')
const acceptedPath = resolve(projectRoot, 'public/yizi-idioms.json')
const migrationPath = resolve(projectRoot, 'supabase/migrations/20261122121000_seed_yizi_qianjin_bank.sql')
await Promise.all([dirname(dataPath), dirname(acceptedPath), dirname(migrationPath)].map((folder) => mkdir(folder, { recursive: true })))
await writeFile(dataPath, `${JSON.stringify({
  source: {
    repository: `https://github.com/${UPSTREAM_REPOSITORY}`,
    commit: UPSTREAM_COMMIT,
    syncedOn: '2026-11-22',
  },
  questions,
  commonIdioms,
}, null, 2)}\n`, 'utf8')
await writeFile(acceptedPath, `${JSON.stringify({
  sourceCommit: UPSTREAM_COMMIT,
  idioms: acceptedIdioms,
})}\n`, 'utf8')
await writeFile(migrationPath, buildSeedMigration(questions, commonIdioms, acceptedIdioms), 'utf8')

