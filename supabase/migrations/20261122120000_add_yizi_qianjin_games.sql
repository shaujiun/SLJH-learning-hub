drop policy if exists yizi_questions_published_read on public.yizi_questions;
create policy yizi_questions_published_read on public.yizi_questions
for select to anon, authenticated
using (status = 'published');

drop policy if exists yizi_questions_admin_all on public.yizi_questions;
create policy yizi_questions_admin_all on public.yizi_questions
for all to authenticated
using (public.can_manage_yizi_questions())
with check (public.can_manage_yizi_questions());

drop policy if exists yizi_lexicon_admin_read on public.yizi_idiom_lexicon;
create policy yizi_lexicon_admin_read on public.yizi_idiom_lexicon
for select to authenticated
using (public.can_manage_yizi_questions());

drop policy if exists yizi_attempts_student_read on public.yizi_attempts;
create policy yizi_attempts_student_read on public.yizi_attempts
for select to authenticated
using (exists (
  select 1 from public.students student
  where student.id = yizi_attempts.student_id
    and student.profile_id = auth.uid()
));

drop policy if exists yizi_attempts_admin_read on public.yizi_attempts;
create policy yizi_attempts_admin_read on public.yizi_attempts
for select to authenticated
using (public.can_manage_yizi_questions());

revoke all on public.yizi_questions, public.yizi_idiom_lexicon, public.yizi_attempts,
  public.yizi_rooms, public.yizi_room_players, public.yizi_room_moves from public, anon, authenticated;
grant select on public.yizi_questions to anon, authenticated;
grant insert, update, delete on public.yizi_questions to authenticated;
grant select on public.yizi_idiom_lexicon, public.yizi_attempts to authenticated;

create or replace function public.record_yizi_attempt(
  p_question_id uuid,
  p_game_type text,
  p_mode_code text,
  p_answer_text text,
  p_is_correct boolean,
  p_score integer,
  p_duration_ms integer,
  p_metadata jsonb default '{}'::jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  current_student_id uuid;
  attempt_id uuid;
begin
  select student.id into current_student_id
  from public.students student
  join public.contact_book_profiles profile on profile.id = student.profile_id
  where student.profile_id = auth.uid()
    and student.is_active = true
    and profile.user_type = 'student'
    and profile.approval_status = 'approved'
    and profile.is_active = true
  limit 1;

  if current_student_id is null then
    raise exception using errcode = 'P0001', message = 'student_required';
  end if;
  if p_game_type not in ('remove_part', 'four_sayings', 'component_pairs', 'idiom_board') then
    raise exception using errcode = 'P0001', message = 'yizi_game_type_invalid';
  end if;

  insert into public.yizi_attempts (
    student_id, question_id, game_type, mode_code, answer_text,
    is_correct, score, duration_ms, metadata
  ) values (
    current_student_id, p_question_id, p_game_type,
    left(coalesce(nullif(trim(p_mode_code), ''), 'untimed'), 40),
    left(coalesce(p_answer_text, ''), 120), coalesce(p_is_correct, false),
    greatest(coalesce(p_score, 0), 0), greatest(coalesce(p_duration_ms, 0), 0),
    coalesce(p_metadata, '{}'::jsonb)
  ) returning id into attempt_id;
  return attempt_id;
end;
$$;

revoke all on function public.record_yizi_attempt(uuid,text,text,text,boolean,integer,integer,jsonb) from public, anon;
grant execute on function public.record_yizi_attempt(uuid,text,text,text,boolean,integer,integer,jsonb) to authenticated;

