-- 一字千金文字挑戰：題庫、作答紀錄、成語字庫與隻字片語房間。

create or replace function public.can_manage_yizi_questions()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.can_manage_word_grid_puzzles();
$$;

revoke all on function public.can_manage_yizi_questions() from public, anon;
grant execute on function public.can_manage_yizi_questions() to authenticated;

create table if not exists public.yizi_questions (
  id uuid primary key default gen_random_uuid(),
  stable_key text not null unique,
  game_type text not null check (game_type in ('remove_part', 'four_sayings', 'component_pairs')),
  difficulty smallint not null default 1 check (difficulty between 1 and 3),
  prompt_data jsonb not null default '{}'::jsonb check (jsonb_typeof(prompt_data) = 'object'),
  answer_data jsonb not null default '{}'::jsonb check (jsonb_typeof(answer_data) = 'object'),
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  source_label text not null default '',
  source_url text not null default '',
  source_commit text not null default '',
  created_by uuid references public.contact_book_profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists yizi_questions_catalog_idx
  on public.yizi_questions(game_type, status, difficulty, updated_at desc);

create table if not exists public.yizi_idiom_lexicon (
  phrase text primary key check (char_length(phrase) = 4),
  is_common boolean not null default false,
  common_rank integer,
  source_commit text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists yizi_idiom_common_idx
  on public.yizi_idiom_lexicon(is_common, common_rank)
  where is_common = true;

create table if not exists public.yizi_attempts (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.students(id) on delete cascade,
  question_id uuid references public.yizi_questions(id) on delete set null,
  game_type text not null check (game_type in ('remove_part', 'four_sayings', 'component_pairs', 'idiom_board')),
  mode_code text not null default 'untimed',
  answer_text text not null default '',
  is_correct boolean not null default false,
  score integer not null default 0 check (score >= 0),
  duration_ms integer check (duration_ms is null or duration_ms >= 0),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now()
);

create index if not exists yizi_attempts_student_game_idx
  on public.yizi_attempts(student_id, game_type, created_at desc);

create table if not exists public.yizi_rooms (
  id uuid primary key default gen_random_uuid(),
  room_code text not null unique check (room_code ~ '^[0-9]{6}$'),
  status text not null default 'waiting' check (status in ('waiting', 'playing', 'finished', 'closed')),
  time_limit_seconds integer not null default 60 check (time_limit_seconds in (60, 90, 120)),
  board jsonb not null default '{}'::jsonb check (jsonb_typeof(board) = 'object'),
  used_idioms text[] not null default '{}'::text[],
  current_seat smallint check (current_seat in (1, 2)),
  winner_seat smallint check (winner_seat in (1, 2)),
  seed_char text not null default '' check (char_length(seed_char) <= 1),
  turn_started_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '12 hours')
);

create table if not exists public.yizi_room_players (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.yizi_rooms(id) on delete cascade,
  seat_no smallint not null check (seat_no in (1, 2)),
  seat_token uuid not null default gen_random_uuid() unique,
  nickname text not null check (char_length(nickname) between 1 and 12),
  student_id uuid references public.students(id) on delete set null,
  status text not null default 'connected' check (status in ('connected', 'left', 'forfeited')),
  score integer not null default 0,
  last_seen_at timestamptz not null default now(),
  joined_at timestamptz not null default now(),
  unique (room_id, seat_no),
  unique (room_id, nickname)
);

create table if not exists public.yizi_room_moves (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.yizi_rooms(id) on delete cascade,
  player_id uuid not null references public.yizi_room_players(id) on delete cascade,
  move_no integer not null,
  phrase text not null check (char_length(phrase) = 4),
  start_row smallint not null,
  start_column smallint not null,
  direction text not null check (direction in ('R', 'L', 'D', 'U', 'DR', 'UL', 'DL', 'UR')),
  placed_at timestamptz not null default now(),
  unique (room_id, move_no)
);

create index if not exists yizi_room_players_room_idx on public.yizi_room_players(room_id, seat_no);
create index if not exists yizi_room_moves_room_idx on public.yizi_room_moves(room_id, move_no);

