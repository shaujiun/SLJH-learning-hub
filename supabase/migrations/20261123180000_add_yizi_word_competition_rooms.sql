-- 去無成字與成雙成對多人競賽。
-- 一般房最多 8 人、全班房最多 36 人；成雙成對另支援逐題輪流淘汰制。

create table if not exists public.yizi_word_competition_rooms (
  id uuid primary key default gen_random_uuid(),
  room_code text not null unique check (room_code ~ '^[0-9]{6}$'),
  game_type text not null check (game_type in ('remove_part', 'component_pairs')),
  competition_mode text not null default 'points' check (competition_mode in ('points', 'turns')),
  input_mode text not null check (input_mode in ('keyboard', 'handwriting')),
  difficulty smallint not null default 0 check (difficulty between 0 and 3),
  time_limit_seconds integer not null check (time_limit_seconds in (30, 60, 90)),
  question_count smallint not null check (question_count in (5, 10)),
  player_limit smallint not null default 8 check (player_limit in (8, 36)),
  status text not null default 'waiting' check (status in ('waiting', 'playing', 'finished', 'closed')),
  question_ids uuid[] not null default '{}'::uuid[],
  current_round smallint not null default 0,
  round_started_at timestamptz,
  round_found_answers text[] not null default '{}'::text[],
  current_turn_seat smallint,
  turn_started_at timestamptz,
  winner_seat smallint check (winner_seat is null or winner_seat between 1 and 36),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '12 hours'),
  check (game_type = 'component_pairs' or competition_mode = 'points')
);

create table if not exists public.yizi_word_competition_players (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.yizi_word_competition_rooms(id) on delete cascade,
  seat_no smallint not null check (seat_no between 1 and 36),
  seat_token uuid not null default gen_random_uuid() unique,
  nickname text not null check (char_length(nickname) between 1 and 12),
  student_id uuid references public.students(id) on delete set null,
  status text not null default 'connected' check (status in ('connected', 'forfeited', 'left')),
  score integer not null default 0 check (score >= 0),
  last_seen_at timestamptz not null default now(),
  joined_at timestamptz not null default now(),
  unique (room_id, seat_no),
  unique (room_id, nickname)
);

create table if not exists public.yizi_word_competition_round_players (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.yizi_word_competition_rooms(id) on delete cascade,
  player_id uuid not null references public.yizi_word_competition_players(id) on delete cascade,
  round_no smallint not null check (round_no > 0),
  status text not null default 'active' check (status in ('active', 'done', 'failed', 'eliminated', 'timed_out')),
  found_answers text[] not null default '{}'::text[],
  attempt_count integer not null default 0 check (attempt_count >= 0),
  score_awarded integer not null default 0 check (score_awarded >= 0),
  last_answer text not null default '',
  last_answer_correct boolean,
  updated_at timestamptz not null default now(),
  unique (room_id, player_id, round_no)
);

create index if not exists yizi_word_competition_players_room_idx
  on public.yizi_word_competition_players(room_id, seat_no);
create index if not exists yizi_word_competition_round_players_idx
  on public.yizi_word_competition_round_players(room_id, round_no, status);

alter table public.yizi_word_competition_rooms enable row level security;
alter table public.yizi_word_competition_players enable row level security;
alter table public.yizi_word_competition_round_players enable row level security;

revoke all on public.yizi_word_competition_rooms, public.yizi_word_competition_players,
  public.yizi_word_competition_round_players from public, anon, authenticated;

create or replace function public.yizi_word_competition_normalize(p_value text)
returns text
language sql
immutable
set search_path = public
as $$
  select regexp_replace(coalesce(p_value, ''), '[[:space:]　，、。；：！!？?（）()「」『』]', '', 'g');
$$;

create or replace function public.yizi_word_competition_answer_is_correct(p_question_id uuid, p_answer text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.yizi_questions question,
      jsonb_array_elements_text(
        coalesce(question.answer_data -> 'accepted', '[]'::jsonb)
        || coalesce(question.answer_data -> 'extra', '[]'::jsonb)
      ) accepted(answer)
    where question.id = p_question_id
      and public.yizi_word_competition_normalize(accepted.answer)
        = public.yizi_word_competition_normalize(p_answer)
  );
$$;

create or replace function public.yizi_word_competition_answer_count(p_question_id uuid)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select count(distinct public.yizi_word_competition_normalize(accepted.answer))::integer
  from public.yizi_questions question,
    jsonb_array_elements_text(
      coalesce(question.answer_data -> 'accepted', '[]'::jsonb)
      || coalesce(question.answer_data -> 'extra', '[]'::jsonb)
    ) accepted(answer)
  where question.id = p_question_id;
$$;

create or replace function public.yizi_word_competition_create_round(p_room_id uuid, p_round_no integer)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_room public.yizi_word_competition_rooms;
  first_seat smallint;
begin
  select * into selected_room from public.yizi_word_competition_rooms where id = p_room_id for update;
  insert into public.yizi_word_competition_round_players(room_id, player_id, round_no)
  select p_room_id, player.id, p_round_no
  from public.yizi_word_competition_players player
  where player.room_id = p_room_id and player.status = 'connected'
  on conflict (room_id, player_id, round_no) do nothing;

  select min(seat_no) into first_seat from public.yizi_word_competition_players
  where room_id = p_room_id and status = 'connected';
  update public.yizi_word_competition_rooms set
    round_started_at = now(), round_found_answers = '{}'::text[],
    current_turn_seat = case when competition_mode = 'turns' then first_seat else null end,
    turn_started_at = case when competition_mode = 'turns' then now() else null end,
    updated_at = now()
  where id = p_room_id;
end;
$$;

create or replace function public.yizi_word_competition_finish_room(p_room_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  best_score integer;
  best_count integer;
  winning_seat smallint;
begin
  select max(score) into best_score from public.yizi_word_competition_players
  where room_id = p_room_id and status = 'connected';
  select count(*), min(seat_no) into best_count, winning_seat
  from public.yizi_word_competition_players
  where room_id = p_room_id and status = 'connected' and score = best_score;
  update public.yizi_word_competition_rooms set
    status = 'finished', winner_seat = case when best_count = 1 then winning_seat else null end,
    updated_at = now()
  where id = p_room_id and status = 'playing';
end;
$$;

create or replace function public.yizi_word_competition_advance(p_room_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_room public.yizi_word_competition_rooms;
  selected_question_id uuid;
  accepted_count integer;
  active_count integer;
  connected_count integer;
begin
  select * into selected_room from public.yizi_word_competition_rooms where id = p_room_id for update;
  if selected_room.id is null or selected_room.status <> 'playing' then return; end if;
  select count(*) into connected_count from public.yizi_word_competition_players
  where room_id = p_room_id and status = 'connected';
  if connected_count <= 1 then
    perform public.yizi_word_competition_finish_room(p_room_id);
    return;
  end if;

  if selected_room.competition_mode = 'turns' then
    selected_question_id := selected_room.question_ids[selected_room.current_round];
    accepted_count := public.yizi_word_competition_answer_count(selected_question_id);
    select count(*) into active_count
    from public.yizi_word_competition_round_players state
    join public.yizi_word_competition_players player on player.id = state.player_id
    where state.room_id = p_room_id and state.round_no = selected_room.current_round
      and state.status = 'active' and player.status = 'connected';
    if active_count > 0 and cardinality(selected_room.round_found_answers) < accepted_count then return; end if;
  elsif exists (
    select 1 from public.yizi_word_competition_round_players state
    join public.yizi_word_competition_players player on player.id = state.player_id
    where state.room_id = p_room_id and state.round_no = selected_room.current_round
      and state.status = 'active' and player.status = 'connected'
  ) then return;
  end if;

  if selected_room.current_round >= selected_room.question_count then
    perform public.yizi_word_competition_finish_room(p_room_id);
    return;
  end if;
  update public.yizi_word_competition_rooms set current_round = current_round + 1, updated_at = now()
  where id = p_room_id returning * into selected_room;
  perform public.yizi_word_competition_create_round(p_room_id, selected_room.current_round);
end;
$$;

create or replace function public.yizi_word_competition_next_turn(p_room_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_room public.yizi_word_competition_rooms;
  next_seat smallint;
  previous_round smallint;
begin
  select * into selected_room from public.yizi_word_competition_rooms where id = p_room_id for update;
  if selected_room.id is null or selected_room.status <> 'playing' or selected_room.competition_mode <> 'turns' then return; end if;
  previous_round := selected_room.current_round;
  perform public.yizi_word_competition_advance(p_room_id);
  select * into selected_room from public.yizi_word_competition_rooms where id = p_room_id;
  if selected_room.status <> 'playing' or selected_room.current_round <> previous_round then return; end if;

  select min(player.seat_no) into next_seat
  from public.yizi_word_competition_round_players state
  join public.yizi_word_competition_players player on player.id = state.player_id
  where state.room_id = p_room_id and state.round_no = selected_room.current_round
    and state.status = 'active' and player.status = 'connected'
    and player.seat_no > coalesce(selected_room.current_turn_seat, 0);
  if next_seat is null then
    select min(player.seat_no) into next_seat
    from public.yizi_word_competition_round_players state
    join public.yizi_word_competition_players player on player.id = state.player_id
    where state.room_id = p_room_id and state.round_no = selected_room.current_round
      and state.status = 'active' and player.status = 'connected';
  end if;
  update public.yizi_word_competition_rooms
  set current_turn_seat = next_seat, turn_started_at = now(), updated_at = now()
  where id = p_room_id and status = 'playing';
end;
$$;

create or replace function public.yizi_word_competition_expire(p_room_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_room public.yizi_word_competition_rooms;
  selected_player_id uuid;
begin
  select * into selected_room from public.yizi_word_competition_rooms where id = p_room_id for update;
  if selected_room.id is null or selected_room.status <> 'playing' then return; end if;
  if selected_room.competition_mode = 'turns' then
    if now() < selected_room.turn_started_at + make_interval(secs => selected_room.time_limit_seconds) then return; end if;
    select id into selected_player_id from public.yizi_word_competition_players
    where room_id = p_room_id and seat_no = selected_room.current_turn_seat and status = 'connected';
    update public.yizi_word_competition_round_players
    set status = 'timed_out', updated_at = now()
    where room_id = p_room_id and player_id = selected_player_id
      and round_no = selected_room.current_round and status = 'active';
    perform public.yizi_word_competition_next_turn(p_room_id);
  else
    if now() < selected_room.round_started_at + make_interval(secs => selected_room.time_limit_seconds) then return; end if;
    update public.yizi_word_competition_round_players state set status = 'timed_out', updated_at = now()
    from public.yizi_word_competition_players player
    where state.room_id = p_room_id and state.round_no = selected_room.current_round
      and state.status = 'active' and state.player_id = player.id and player.status = 'connected';
    perform public.yizi_word_competition_advance(p_room_id);
  end if;
end;
$$;

create or replace function public.yizi_word_competition_create_room(
  p_nickname text,
  p_game_type text,
  p_competition_mode text,
  p_input_mode text,
  p_difficulty integer,
  p_time_limit_seconds integer,
  p_question_count integer,
  p_player_limit integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_nickname text := trim(coalesce(p_nickname, ''));
  generated_code text;
  created_room public.yizi_word_competition_rooms;
  created_player public.yizi_word_competition_players;
  attempt_count integer := 0;
begin
  if char_length(normalized_nickname) < 1 or char_length(normalized_nickname) > 12 then
    raise exception using errcode = 'P0001', message = 'yizi_nickname_invalid';
  end if;
  if p_game_type not in ('remove_part', 'component_pairs') then
    raise exception using errcode = 'P0001', message = 'yizi_word_game_invalid';
  end if;
  if p_competition_mode not in ('points', 'turns') or (p_game_type = 'remove_part' and p_competition_mode <> 'points') then
    raise exception using errcode = 'P0001', message = 'yizi_word_mode_invalid';
  end if;
  if p_input_mode not in ('keyboard', 'handwriting') then
    raise exception using errcode = 'P0001', message = 'yizi_answer_mode_invalid';
  end if;
  if p_difficulty not between 0 and 3 then raise exception using errcode = 'P0001', message = 'yizi_difficulty_invalid'; end if;
  if p_time_limit_seconds not in (30, 60, 90) then raise exception using errcode = 'P0001', message = 'yizi_word_time_invalid'; end if;
  if p_question_count not in (5, 10) then raise exception using errcode = 'P0001', message = 'yizi_question_count_invalid'; end if;
  if p_player_limit not in (8, 36) then raise exception using errcode = 'P0001', message = 'yizi_player_limit_invalid'; end if;
  loop
    attempt_count := attempt_count + 1;
    generated_code := lpad(floor(random() * 1000000)::integer::text, 6, '0');
    exit when not exists (
      select 1 from public.yizi_word_competition_rooms room
      where room.room_code = generated_code and room.expires_at > now() and room.status <> 'closed'
    );
    if attempt_count >= 60 then raise exception using errcode = 'P0001', message = 'yizi_room_code_unavailable'; end if;
  end loop;
  insert into public.yizi_word_competition_rooms(
    room_code, game_type, competition_mode, input_mode, difficulty,
    time_limit_seconds, question_count, player_limit
  ) values (
    generated_code, p_game_type, p_competition_mode, p_input_mode, p_difficulty,
    p_time_limit_seconds, p_question_count, p_player_limit
  ) returning * into created_room;
  insert into public.yizi_word_competition_players(room_id, seat_no, nickname, student_id)
  values (created_room.id, 1, normalized_nickname, public.yizi_current_student_id())
  returning * into created_player;
  return jsonb_build_object('roomCode', created_room.room_code, 'seatToken', created_player.seat_token, 'seatNo', 1, 'gameType', created_room.game_type);
end;
$$;

create or replace function public.yizi_word_competition_join_room(p_room_code text, p_nickname text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_code text := regexp_replace(coalesce(p_room_code, ''), '\D', '', 'g');
  normalized_nickname text := trim(coalesce(p_nickname, ''));
  selected_room public.yizi_word_competition_rooms;
  created_player public.yizi_word_competition_players;
  selected_seat smallint;
begin
  if char_length(normalized_nickname) < 1 or char_length(normalized_nickname) > 12 then
    raise exception using errcode = 'P0001', message = 'yizi_nickname_invalid';
  end if;
  select * into selected_room from public.yizi_word_competition_rooms
  where room_code = normalized_code and expires_at > now() and status = 'waiting' for update;
  if selected_room.id is null then raise exception using errcode = 'P0001', message = 'yizi_room_not_found'; end if;
  if (select count(*) from public.yizi_word_competition_players where room_id = selected_room.id) >= selected_room.player_limit then
    raise exception using errcode = 'P0001', message = 'yizi_room_full';
  end if;
  if exists (select 1 from public.yizi_word_competition_players where room_id = selected_room.id and nickname = normalized_nickname) then
    raise exception using errcode = 'P0001', message = 'yizi_duplicate_nickname';
  end if;
  select seat into selected_seat from generate_series(2, selected_room.player_limit) seat
  where not exists (select 1 from public.yizi_word_competition_players player where player.room_id = selected_room.id and player.seat_no = seat)
  order by seat limit 1;
  if selected_seat is null then raise exception using errcode = 'P0001', message = 'yizi_room_full'; end if;
  insert into public.yizi_word_competition_players(room_id, seat_no, nickname, student_id)
  values (selected_room.id, selected_seat, normalized_nickname, public.yizi_current_student_id())
  returning * into created_player;
  return jsonb_build_object('roomCode', selected_room.room_code, 'seatToken', created_player.seat_token, 'seatNo', selected_seat, 'gameType', selected_room.game_type);
end;
$$;

create or replace function public.yizi_word_competition_start_room(p_room_code text, p_seat_token uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_room public.yizi_word_competition_rooms;
  selected_player public.yizi_word_competition_players;
  chosen_ids uuid[];
  player_count integer;
begin
  select * into selected_room from public.yizi_word_competition_rooms where room_code = p_room_code for update;
  if selected_room.id is null then raise exception using errcode = 'P0001', message = 'yizi_room_not_found'; end if;
  select * into selected_player from public.yizi_word_competition_players
  where room_id = selected_room.id and seat_token = p_seat_token and status = 'connected';
  if selected_player.id is null then raise exception using errcode = 'P0001', message = 'yizi_seat_invalid'; end if;
  if selected_player.seat_no <> 1 then raise exception using errcode = 'P0001', message = 'yizi_host_required'; end if;
  if selected_room.status <> 'waiting' then raise exception using errcode = 'P0001', message = 'yizi_room_started'; end if;
  select count(*) into player_count from public.yizi_word_competition_players
  where room_id = selected_room.id and status = 'connected';
  if player_count < 2 then raise exception using errcode = 'P0001', message = 'yizi_players_incomplete'; end if;
  select array_agg(candidate.id) into chosen_ids from (
    select id from public.yizi_questions
    where game_type = selected_room.game_type and status = 'published'
      and (selected_room.difficulty = 0 or difficulty = selected_room.difficulty)
    order by random() limit selected_room.question_count
  ) candidate;
  if coalesce(cardinality(chosen_ids), 0) < selected_room.question_count then
    raise exception using errcode = 'P0001', message = 'yizi_questions_insufficient';
  end if;
  update public.yizi_word_competition_rooms set
    status = 'playing', question_ids = chosen_ids, current_round = 1, updated_at = now()
  where id = selected_room.id;
  perform public.yizi_word_competition_create_round(selected_room.id, 1);
  return public.yizi_word_competition_snapshot(p_room_code, p_seat_token);
end;
$$;

create or replace function public.yizi_word_competition_snapshot(p_room_code text, p_seat_token uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_room public.yizi_word_competition_rooms;
  selected_player public.yizi_word_competition_players;
  selected_state public.yizi_word_competition_round_players;
  selected_question public.yizi_questions;
  last_question public.yizi_questions;
  last_round_no integer;
  stale_current_turn boolean := false;
begin
  select * into selected_room from public.yizi_word_competition_rooms
  where room_code = p_room_code and expires_at > now() and status <> 'closed';
  if selected_room.id is null then raise exception using errcode = 'P0001', message = 'yizi_room_not_found'; end if;
  select * into selected_player from public.yizi_word_competition_players
  where room_id = selected_room.id and seat_token = p_seat_token;
  if selected_player.id is null then raise exception using errcode = 'P0001', message = 'yizi_seat_invalid'; end if;
  update public.yizi_word_competition_players set last_seen_at = now()
  where id = selected_player.id and status = 'connected';

  if selected_room.status = 'playing' then
    select exists (select 1 from public.yizi_word_competition_players
      where room_id = selected_room.id and seat_no = selected_room.current_turn_seat
        and status = 'connected' and last_seen_at < now() - interval '180 seconds') into stale_current_turn;
    update public.yizi_word_competition_round_players state set status = 'eliminated', updated_at = now()
    from public.yizi_word_competition_players player
    where state.room_id = selected_room.id and state.round_no = selected_room.current_round
      and state.player_id = player.id and state.status = 'active'
      and player.id <> selected_player.id and player.status = 'connected'
      and player.last_seen_at < now() - interval '180 seconds';
    update public.yizi_word_competition_players set status = 'forfeited'
    where room_id = selected_room.id and id <> selected_player.id and status = 'connected'
      and last_seen_at < now() - interval '180 seconds';
    if selected_room.competition_mode = 'turns' and stale_current_turn then
      perform public.yizi_word_competition_next_turn(selected_room.id);
    else
      perform public.yizi_word_competition_advance(selected_room.id);
    end if;
    perform public.yizi_word_competition_expire(selected_room.id);
  end if;
  select * into selected_room from public.yizi_word_competition_rooms where id = selected_room.id;
  if selected_room.status = 'playing' then
    select * into selected_question from public.yizi_questions where id = selected_room.question_ids[selected_room.current_round];
    select * into selected_state from public.yizi_word_competition_round_players
    where room_id = selected_room.id and player_id = selected_player.id and round_no = selected_room.current_round;
  end if;
  last_round_no := case
    when selected_room.status = 'finished' and selected_room.current_round > 0 then selected_room.current_round
    when selected_room.current_round > 1 then selected_room.current_round - 1
    else null end;
  if last_round_no is not null then
    select * into last_question from public.yizi_questions where id = selected_room.question_ids[last_round_no];
  end if;

  return jsonb_build_object(
    'room', jsonb_build_object(
      'roomCode', selected_room.room_code, 'status', selected_room.status,
      'gameType', selected_room.game_type, 'competitionMode', selected_room.competition_mode,
      'inputMode', selected_room.input_mode, 'difficulty', selected_room.difficulty,
      'timeLimitSeconds', selected_room.time_limit_seconds, 'questionCount', selected_room.question_count,
      'playerLimit', selected_room.player_limit, 'currentRound', selected_room.current_round,
      'roundStartedAt', selected_room.round_started_at, 'currentTurnSeat', selected_room.current_turn_seat,
      'turnStartedAt', selected_room.turn_started_at, 'winnerSeat', selected_room.winner_seat,
      'roundFoundAnswers', selected_room.round_found_answers
    ),
    'meSeat', selected_player.seat_no,
    'players', coalesce((select jsonb_agg(jsonb_build_object(
      'seatNo', player.seat_no, 'nickname', player.nickname, 'status', player.status,
      'score', player.score,
      'roundStatus', coalesce(state.status, 'waiting'),
      'roundScore', coalesce(state.score_awarded, 0)
    ) order by player.score desc, player.seat_no)
      from public.yizi_word_competition_players player
      left join public.yizi_word_competition_round_players state
        on state.player_id = player.id and state.round_no = selected_room.current_round
      where player.room_id = selected_room.id), '[]'::jsonb),
    'currentQuestion', case when selected_question.id is null then null else jsonb_build_object(
      'id', selected_question.id, 'stableKey', selected_question.stable_key,
      'difficulty', selected_question.difficulty, 'prompt', selected_question.prompt_data
    ) end,
    'myRound', case when selected_state.id is null then null else jsonb_build_object(
      'status', selected_state.status, 'foundAnswers', selected_state.found_answers,
      'attemptCount', selected_state.attempt_count, 'scoreAwarded', selected_state.score_awarded,
      'lastAnswer', selected_state.last_answer, 'lastAnswerCorrect', selected_state.last_answer_correct
    ) end,
    'lastRound', case when last_question.id is null then null else jsonb_build_object(
      'roundNo', last_round_no,
      'answers', coalesce(last_question.answer_data -> 'accepted', '[]'::jsonb)
        || coalesce(last_question.answer_data -> 'extra', '[]'::jsonb)
    ) end
  );
end;
$$;

create or replace function public.yizi_word_competition_submit_answer(
  p_room_code text,
  p_seat_token uuid,
  p_answer text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_room public.yizi_word_competition_rooms;
  selected_player public.yizi_word_competition_players;
  selected_state public.yizi_word_competition_round_players;
  question_id uuid;
  normalized_answer text := public.yizi_word_competition_normalize(p_answer);
  is_correct boolean;
  accepted_count integer;
begin
  select * into selected_room from public.yizi_word_competition_rooms where room_code = p_room_code for update;
  select * into selected_player from public.yizi_word_competition_players
  where room_id = selected_room.id and seat_token = p_seat_token and status = 'connected';
  if selected_player.id is null then raise exception using errcode = 'P0001', message = 'yizi_seat_invalid'; end if;
  if selected_room.status <> 'playing' then raise exception using errcode = 'P0001', message = 'yizi_room_not_playing'; end if;
  perform public.yizi_word_competition_expire(selected_room.id);
  select * into selected_room from public.yizi_word_competition_rooms where id = selected_room.id;
  if selected_room.status <> 'playing' then return public.yizi_word_competition_snapshot(p_room_code, p_seat_token); end if;
  if selected_room.competition_mode = 'turns' and selected_room.current_turn_seat <> selected_player.seat_no then
    raise exception using errcode = 'P0001', message = 'yizi_not_your_turn';
  end if;
  select * into selected_state from public.yizi_word_competition_round_players
  where room_id = selected_room.id and player_id = selected_player.id and round_no = selected_room.current_round for update;
  if selected_state.status <> 'active' then raise exception using errcode = 'P0001', message = 'yizi_word_round_inactive'; end if;
  if char_length(normalized_answer) <> 1 then raise exception using errcode = 'P0001', message = 'yizi_word_answer_invalid'; end if;

  question_id := selected_room.question_ids[selected_room.current_round];
  is_correct := public.yizi_word_competition_answer_is_correct(question_id, normalized_answer);
  accepted_count := public.yizi_word_competition_answer_count(question_id);
  if selected_room.game_type = 'remove_part' then
    if is_correct then
      update public.yizi_word_competition_round_players set
        status = 'done', attempt_count = attempt_count + 1, score_awarded = 1,
        last_answer = normalized_answer, last_answer_correct = true, updated_at = now()
      where id = selected_state.id;
      update public.yizi_word_competition_players set score = score + 1, last_seen_at = now() where id = selected_player.id;
    elsif selected_state.attempt_count < 1 then
      update public.yizi_word_competition_round_players set
        attempt_count = attempt_count + 1, last_answer = normalized_answer,
        last_answer_correct = false, updated_at = now()
      where id = selected_state.id;
    else
      update public.yizi_word_competition_round_players set
        status = 'failed', attempt_count = attempt_count + 1, last_answer = normalized_answer,
        last_answer_correct = false, updated_at = now()
      where id = selected_state.id;
    end if;
    perform public.yizi_word_competition_advance(selected_room.id);
  elsif selected_room.competition_mode = 'points' then
    if is_correct and not (normalized_answer = any(selected_state.found_answers)) then
      update public.yizi_word_competition_round_players set
        found_answers = array_append(found_answers, normalized_answer),
        attempt_count = attempt_count + 1, score_awarded = score_awarded + 1,
        status = case when cardinality(found_answers) + 1 >= accepted_count then 'done' else status end,
        last_answer = normalized_answer, last_answer_correct = true, updated_at = now()
      where id = selected_state.id;
      update public.yizi_word_competition_players set score = score + 1, last_seen_at = now() where id = selected_player.id;
    else
      update public.yizi_word_competition_round_players set
        attempt_count = attempt_count + 1, last_answer = normalized_answer,
        last_answer_correct = false, updated_at = now()
      where id = selected_state.id;
    end if;
    perform public.yizi_word_competition_advance(selected_room.id);
  else
    if is_correct and not (normalized_answer = any(selected_room.round_found_answers)) then
      update public.yizi_word_competition_rooms set
        round_found_answers = array_append(round_found_answers, normalized_answer), updated_at = now()
      where id = selected_room.id;
      update public.yizi_word_competition_round_players set
        found_answers = array_append(found_answers, normalized_answer),
        attempt_count = attempt_count + 1, score_awarded = score_awarded + 1,
        last_answer = normalized_answer, last_answer_correct = true, updated_at = now()
      where id = selected_state.id;
      update public.yizi_word_competition_players set score = score + 1, last_seen_at = now() where id = selected_player.id;
    else
      update public.yizi_word_competition_round_players set
        status = 'eliminated', attempt_count = attempt_count + 1,
        last_answer = normalized_answer, last_answer_correct = false, updated_at = now()
      where id = selected_state.id;
    end if;
    perform public.yizi_word_competition_next_turn(selected_room.id);
  end if;
  return public.yizi_word_competition_snapshot(p_room_code, p_seat_token);
end;
$$;

create or replace function public.yizi_word_competition_give_up(p_room_code text, p_seat_token uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_room public.yizi_word_competition_rooms;
  selected_player public.yizi_word_competition_players;
begin
  select * into selected_room from public.yizi_word_competition_rooms where room_code = p_room_code for update;
  select * into selected_player from public.yizi_word_competition_players
  where room_id = selected_room.id and seat_token = p_seat_token and status = 'connected';
  if selected_player.id is null then raise exception using errcode = 'P0001', message = 'yizi_seat_invalid'; end if;
  if selected_room.status <> 'playing' then raise exception using errcode = 'P0001', message = 'yizi_room_not_playing'; end if;
  if selected_room.competition_mode = 'turns' and selected_room.current_turn_seat <> selected_player.seat_no then
    raise exception using errcode = 'P0001', message = 'yizi_not_your_turn';
  end if;
  update public.yizi_word_competition_round_players set
    status = case when selected_room.competition_mode = 'turns' then 'eliminated' else 'done' end,
    last_answer = '', last_answer_correct = false, updated_at = now()
  where room_id = selected_room.id and player_id = selected_player.id
    and round_no = selected_room.current_round and status = 'active';
  if selected_room.competition_mode = 'turns' then
    perform public.yizi_word_competition_next_turn(selected_room.id);
  else
    perform public.yizi_word_competition_advance(selected_room.id);
  end if;
  return public.yizi_word_competition_snapshot(p_room_code, p_seat_token);
end;
$$;

create or replace function public.yizi_word_competition_leave_room(p_room_code text, p_seat_token uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_room public.yizi_word_competition_rooms;
  selected_player public.yizi_word_competition_players;
  was_current_turn boolean := false;
begin
  select * into selected_room from public.yizi_word_competition_rooms where room_code = p_room_code for update;
  if selected_room.id is null then return jsonb_build_object('closed', true); end if;
  select * into selected_player from public.yizi_word_competition_players
  where room_id = selected_room.id and seat_token = p_seat_token;
  if selected_player.id is null then raise exception using errcode = 'P0001', message = 'yizi_seat_invalid'; end if;
  if selected_room.status = 'waiting' then
    if selected_player.seat_no = 1 then
      update public.yizi_word_competition_rooms set status = 'closed', updated_at = now() where id = selected_room.id;
    else
      delete from public.yizi_word_competition_players where id = selected_player.id;
    end if;
  elsif selected_room.status = 'playing' and selected_player.status = 'connected' then
    was_current_turn := selected_room.competition_mode = 'turns' and selected_room.current_turn_seat = selected_player.seat_no;
    update public.yizi_word_competition_round_players set status = 'eliminated', updated_at = now()
    where room_id = selected_room.id and player_id = selected_player.id
      and round_no = selected_room.current_round and status = 'active';
    update public.yizi_word_competition_players set status = 'forfeited', last_seen_at = now() where id = selected_player.id;
    if was_current_turn then perform public.yizi_word_competition_next_turn(selected_room.id);
    else perform public.yizi_word_competition_advance(selected_room.id); end if;
  end if;
  return jsonb_build_object('closed', true);
end;
$$;

