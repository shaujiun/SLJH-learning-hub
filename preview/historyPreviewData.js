export function createHistoryPreviewData() {
  const chapters = chapterSeeds.map(([volumeNo, semester, chapterNo, title, startPage]) => {
    const chapterCode = `hanlin-8-${semester}-0${chapterNo}`
    return {
      id: `preview-${chapterCode}`,
      chapterCode,
      curriculumEdition: '翰林',
      schoolYearLabel: semester === 1 ? '115' : '114',
      gradeLevel: 8,
      semester,
      volumeNo,
      chapterNo,
      title,
      startPage,
      displayOrder: volumeNo * 1000 + chapterNo * 10,
      isActive: true,
    }
  })
  const chapterByKey = new Map(chapters.map((chapter) => [`${chapter.volumeNo}-${chapter.chapterNo}`, chapter]))
  const events = eventSeeds.map(([eventCode, volumeNo, chapterNo, title, startYear, endYear, region, category, summary, causeText, processText, impactText], index) => {
    const chapter = chapterByKey.get(`${volumeNo}-${chapterNo}`)
    return {
      id: `preview-${eventCode}`,
      eventCode,
      chapterId: chapter.id,
      chapter,
      title,
      startYear,
      endYear,
      displayDate: '',
      region,
      category,
      importance: index % 4 === 0 ? 3 : 2,
      summary,
      causeText,
      processText,
      impactText,
      people: [],
      keywords: [],
      imageUrl: '',
      imageSource: '',
      imageSourceUrl: '',
      resourceUrl: '',
      sourceNote: '本機預覽示範資料，不會寫入 Supabase。',
      pastQuestions: [],
      practiceQuestions: [{
        id: `practice-${eventCode}`,
        source: '本機預覽自編題',
        prompt: `請用一至兩句話說明「${title}」造成的主要影響。`,
        answer: impactText,
        explanation: '作答時應說明事件後續造成的政治、社會或區域變化。',
      }],
      displayOrder: index * 10,
      status: 'published',
      publishedAt: null,
      updatedAt: null,
    }
  })
  return {
    chapters,
    events,
    canManage: false,
    position: null,
    previewMode: true,
  }
}
